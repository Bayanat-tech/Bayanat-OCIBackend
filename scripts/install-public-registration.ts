// Run after install-company-subscriptions.js. Creates no tenant, account or invoice.
import 'dotenv/config';
import oracledb from 'oracledb';
try { oracledb.initOracleClient({libDir:process.env.ORACLE_INSTANT_CLIENT_PATH}); } catch(e:any) {if(e.code!=='NJS-077')throw e;}
(async()=>{
 const c=await oracledb.getConnection({user:process.env.ORACLE_USER,password:process.env.ORACLE_PASSWORD,connectString:process.env.ORACLE_CONNECTION_STRING});
 try {
  const create=async(sql:string)=>{try{await c.execute(sql);}catch(e:any){if(e.errorNum!==955)throw e;}};
  await create(`CREATE TABLE CUSTOMERS.SEC_REGISTRATION_CONFIG(CONFIG_ID NUMBER PRIMARY KEY,CONFIG_JSON CLOB NOT NULL,UPDATED_BY VARCHAR2(100),UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,CONSTRAINT CK_REG_CONFIG_SINGLE CHECK(CONFIG_ID=1))`);
  await c.execute(`MERGE INTO CUSTOMERS.SEC_REGISTRATION_CONFIG d USING(SELECT 1 CONFIG_ID FROM DUAL)s ON(d.CONFIG_ID=s.CONFIG_ID) WHEN NOT MATCHED THEN INSERT(CONFIG_ID,CONFIG_JSON,UPDATED_BY) VALUES(1,:config,'INSTALL')`,{config:JSON.stringify({enabled:false,tenant:'',currency:'INR',offers:[],version:0})});
  await create(`CREATE TABLE CUSTOMERS.SEC_PUBLIC_SIGNUP(
    SIGNUP_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,TOKEN_HASH VARCHAR2(64) UNIQUE,PAYLOAD CLOB NOT NULL,
    TENANT_ID VARCHAR2(100) NOT NULL,COMPANY_CODE VARCHAR2(20) NOT NULL,
    STATE VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,EXPIRES_AT TIMESTAMP NOT NULL,TRIAL_END_AT TIMESTAMP,
    WELCOME_STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,MAIL_ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
    SETUP_STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CAST(SYS_EXTRACT_UTC(SYSTIMESTAMP) AS TIMESTAMP),
    UPDATED_AT TIMESTAMP DEFAULT CAST(SYS_EXTRACT_UTC(SYSTIMESTAMP) AS TIMESTAMP),
    CONSTRAINT CK_PUBLIC_SIGNUP_STATE CHECK(STATE IN ('PENDING','COMPLETE')),
    CONSTRAINT CK_PUBLIC_SIGNUP_MAIL CHECK(WELCOME_STATUS IN ('PENDING','SENDING','SENT','FAILED')),
    CONSTRAINT CK_PUBLIC_SIGNUP_SETUP CHECK(SETUP_STATUS IN ('PENDING','READY')))`);
  await c.commit();console.log('Public registration tables ready. Registration remains disabled; existing companies are unchanged.');
 }finally{await c.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
