//subscription settings API.
require('dotenv').config({ quiet: true });
const db = require('oracledb');
try { db.initOracleClient({ libDir: process.env.ORACLE_INSTANT_CLIENT_PATH }); } catch (e) { if (e.code !== 'NJS-077') throw e; }
(async () => {
  const c = await db.getConnection({ user: process.env.ORACLE_USER, password: process.env.ORACLE_PASSWORD, connectString: process.env.ORACLE_CONNECTION_STRING });
  try {
    await c.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE CUSTOMERS.SEC_COMPANY_SUBSCRIPTION (
      TENANT_ID VARCHAR2(100) NOT NULL, COMPANY_CODE VARCHAR2(20) NOT NULL,
      PLAN_NAME VARCHAR2(100), STATUS VARCHAR2(20) DEFAULT ''DRAFT'' NOT NULL,
      BILLING_CYCLE VARCHAR2(20) DEFAULT ''MONTHLY'' NOT NULL, CURRENCY VARCHAR2(3),
      AMOUNT NUMBER(16,2), NEXT_BILL_DATE DATE, BILLING_REFERENCE VARCHAR2(100), NOTES VARCHAR2(1000),
      VERSION_NO NUMBER DEFAULT 1 NOT NULL, UPDATED_BY VARCHAR2(100), UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_SEC_COMPANY_SUBSCRIPTION PRIMARY KEY (TENANT_ID,COMPANY_CODE),
      CONSTRAINT CK_SEC_COMPANY_SUB_STATUS CHECK (STATUS IN (''DRAFT'',''ACTIVE'',''PAUSED'',''CLOSED'')),
      CONSTRAINT CK_SEC_COMPANY_SUB_CYCLE CHECK (BILLING_CYCLE IN (''MONTHLY'',''QUARTERLY'',''YEARLY'',''CUSTOM'')),
      CONSTRAINT CK_SEC_COMPANY_SUB_AMOUNT CHECK (AMOUNT IS NULL OR AMOUNT>=0)
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);
    // Adding the opt-in column defaults all existing companies to inactive.
    // Subsequent runs preserve deliberate activations.
    for (const definition of [
      "BILLING_ENABLED CHAR(1) DEFAULT 'N' NOT NULL", "START_DATE DATE", "MODULE_CODES VARCHAR2(1000)",
      "BILLING_EMAIL VARCHAR2(254)", "DUE_DAYS NUMBER DEFAULT 0 NOT NULL", "GRACE_DAYS NUMBER DEFAULT 7 NOT NULL",
      "CUSTOM_DAYS NUMBER", "PERIOD_NO NUMBER DEFAULT 0 NOT NULL", "SUSPENDED CHAR(1) DEFAULT 'N' NOT NULL", "CANCEL_ON DATE"
    ]) {
      try { await c.execute(`ALTER TABLE CUSTOMERS.SEC_COMPANY_SUBSCRIPTION ADD (${definition})`); }
      catch (e) { if (e.errorNum !== 1430) throw e; }
    }
    const create = async sql => { try { await c.execute(sql); } catch (e) { if (e.errorNum !== 955) throw e; } };
    await create(`CREATE TABLE CUSTOMERS.SEC_BILLING_INVOICE (
      INVOICE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      TENANT_ID VARCHAR2(100) NOT NULL, COMPANY_CODE VARCHAR2(20) NOT NULL,
      PERIOD_START DATE NOT NULL, PERIOD_END DATE NOT NULL, DUE_DATE DATE NOT NULL, GRACE_END DATE NOT NULL,
      PLAN_NAME VARCHAR2(100), MODULE_CODES VARCHAR2(1000) NOT NULL, CURRENCY VARCHAR2(3) NOT NULL,
      AMOUNT NUMBER(16,2) NOT NULL, STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
      PAYMENT_REFERENCE VARCHAR2(100), PAID_ON DATE, PAID_BY VARCHAR2(100), CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT UK_SEC_BILLING_PERIOD UNIQUE (TENANT_ID,COMPANY_CODE,PERIOD_START),
      CONSTRAINT FK_SEC_BILLING_SUB FOREIGN KEY (TENANT_ID,COMPANY_CODE) REFERENCES CUSTOMERS.SEC_COMPANY_SUBSCRIPTION(TENANT_ID,COMPANY_CODE),
      CONSTRAINT CK_SEC_BILLING_INV_STATUS CHECK (STATUS IN ('PENDING','PAID')),
      CONSTRAINT CK_SEC_BILLING_INV_AMOUNT CHECK (AMOUNT>0),
      CONSTRAINT CK_SEC_BILLING_INV_DATES CHECK (PERIOD_END>=PERIOD_START AND GRACE_END>=DUE_DATE)
    )`);
    await create(`CREATE TABLE CUSTOMERS.SEC_BILLING_REMINDER (
      REMINDER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      INVOICE_ID NUMBER NOT NULL REFERENCES CUSTOMERS.SEC_BILLING_INVOICE(INVOICE_ID),
      KIND VARCHAR2(20) NOT NULL, EMAIL_TO VARCHAR2(254), EMAIL_STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
      ATTEMPTS NUMBER DEFAULT 0 NOT NULL, LAST_ERROR VARCHAR2(200), UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT UK_SEC_BILLING_REMINDER UNIQUE (INVOICE_ID,KIND),
      CONSTRAINT CK_SEC_BILLING_MAIL_STATUS CHECK (EMAIL_STATUS IN ('PENDING','SENDING','SENT','FAILED','SKIPPED')),
      CONSTRAINT CK_SEC_BILLING_KIND CHECK (KIND IN ('ISSUED','OVERDUE','GRACE_EXPIRED'))
    )`);
    console.log('Billing tables are ready. New and previously unconfigured companies have billing inactive; existing settings were preserved.');
  } finally { await c.close(); }
})().catch(e => { console.error(e.message); process.exitCode = 1; });
