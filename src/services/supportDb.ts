export function supportError(message: string, status = 400): never { throw Object.assign(new Error(message), { status }); }
export function text(v: unknown, max = 4000) { const s = String(v ?? '').trim(); if (s.length > max)
    supportError(`Text exceeds ${max} characters`); return s; }
export function identity(u: any) {
    const loginid = text(u?.loginid || u?.LOGINID, 100).toUpperCase(), tenantId = text(u?.tenantId, 80), companyCode = text(u?.company_code, 20);
    if (!loginid || !tenantId || !companyCode)
        supportError('Authenticated login, tenant and company are required', 401);
    return { loginid, tenantId, companyCode };
}
export async function query(c: oracledb.Connection, sql: string, b: any = {}) { return (await c.execute<any>(sql, b, { outFormat: oracledb.OUT_FORMAT_OBJECT, fetchInfo: { BODY: { type: oracledb.STRING }, MESSAGE_TEXT: { type: oracledb.STRING }, DATA_URL: { type: oracledb.STRING } } })).rows || []; }
export async function supportRole(c:oracledb.Connection,u:any):Promise<'admin'|'developer'|'user'>{return nativeSupportRole(c,identity(u));}
export async function withSupportDb<T>(fn: (c: oracledb.Connection) => Promise<T>, write = false) {
    await ensureSupportSchema();
    const c = await oracleDb.getConnection();
    try {
        const r = await fn(c);
        if (write)
            await c.commit();
        return r;
    }
    catch (e) {
        await c.rollback();
        throw e;
    }
    finally {
        await c.close();
    }
}
