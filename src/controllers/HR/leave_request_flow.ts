import { Request, Response } from "express";
import oracledb from "oracledb";
import TenantManager from "../../database/TenantManager";
import { getCurrentTenantId } from "../../middleware/tenantContext.middleware";
import { HrService } from "./MHDL/mh_hr.service";
import { LeaveRequestFlow } from "../../interfaces/leaveRequestFlow.interface"; // adjust path

/** Request body for saving (insert / update) a leave request. */
interface SaveLeaveRequestBody {
  loginId: string;

  companyCode: string;
  requestNumber?: string; // blank = new request, number is generated by the procedure
  employeeCode: string;
  employeeName?: string;
  leaveType?: string;
  requestDate?: string;
  leaveStartDate?: string;
  leaveEndDate?: string;
  remarks?: string;
  halfDay?: string;
  leaveAllowance?: string;
  advPayment?: string;
  causeType?: string;
  airTicket?: string;
  airRoute?: string;
  travelDate?: string;
  travelEndDate?: string;
  nameOfReplacement?: string;
  contactDetailsDuringLeave?: string;
  dutyResumeDate?: string;
  actualResumeDate?: string;
  hod?: string;
  immediateSupervisor?: string;
  deptHead?: string;
  lastAction?: string; // SAVEASDRAFT / SUBMIT / SENTBACK / REJECTED / CANCEL ...
  createdBy?: string;
  uuid?: string;
  flowCode?: string;
  nextActionBy?: string; // SENTBACK only
  sentbackHistory?: string; // SENTBACK only
  cancelRemark?: string; // REJECTED / CANCEL

  leaveDays?: number;
  flowLevelInitial?: number;
  flowLevelRunning?: number;
  flowLevelFinal?: number;
}

// ---------- helpers ----------

const str = (v: unknown): string | null =>
  v === undefined || v === null || String(v).trim() === "" ? null : String(v);

const num = (v: unknown): number | null => {
  if (v === undefined || v === null || v === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
};

const pad = (n: number) => String(n).padStart(2, "0");

// Local-time string so HrService's toISOString() can't shift the date back a day
const dateToLocalString = (d: Date) =>
  `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
  `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;

// LEAVE_START_DATE -> leaveStartDate, Date -> local string
const rowToLeaveRequest = (row: Record<string, any>): LeaveRequestFlow => {
  const out: Record<string, any> = {};
  for (const [key, value] of Object.entries(row)) {
    const camel = key.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
    out[camel] = value instanceof Date ? dateToLocalString(value) : value;
  }
  out.finalApproved = "YES";
  out.leaveReason = out.leaveReason ?? out.remarks; // the table stores the reason in REMARKS
  return out as LeaveRequestFlow;
};

// ---------- controller ----------

export const leaveRequestFlow = async (
  req: Request,
  res: Response
): Promise<void> => {
  let connection : oracledb.Connection;

  try {
    const body = (req.body ?? {}) as SaveLeaveRequestBody;

    if (!body.loginId) {
      res.status(400).json({ success: false, message: "Missing required field 'loginId'" });
      return;
    }
    if (!body.companyCode) {
      res.status(400).json({ success: false, message: "Missing required field 'companyCode'" });
      return;
    }

    // Resolve tenantId from context or fallback to loginId lookup
    let tenantId: string | undefined;
    try {
      tenantId = getCurrentTenantId();
    } catch (e) { }
    if (!tenantId) {
      tenantId = await TenantManager.getTenantForUser(body.loginId);
    }

    if (!tenantId) {
      res.status(400).json({ success: false, message: "Tenant not found for request" });
      return;
    }

    connection = await TenantManager.getConnection(tenantId);

    // 1) Ask the procedure to build the INSERT / UPDATE SQL
    const result = await connection.execute(
      `
      DECLARE
        v_sql CLOB;
        v_req VARCHAR2(50);
      BEGIN
        PROC_BUILD_DYNAMIC_INS_UPD_LEAVE_REQUEST_FLOW(
          P_LOGIN_ID                     => :loginId,
          P_COMPANY_CODE                 => :companyCode,
          P_REQUEST_NUMBER               => :requestNumber,
          P_EMPLOYEE_CODE                => :employeeCode,
          P_EMPLOYEE_NAME                => :employeeName,
          P_LEAVE_TYPE                   => :leaveType,
          P_REQUEST_DATE                 => :requestDate,
          P_LEAVE_START_DATE             => :leaveStartDate,
          P_LEAVE_END_DATE               => :leaveEndDate,
          P_REMARKS                      => :remarks,
          P_HALF_DAY                     => :halfDay,
          P_LEAVE_ALLOWANCE              => :leaveAllowance,
          P_ADV_PAYMENT                  => :advPayment,
          P_CAUSE_TYPE                   => :causeType,
          P_AIR_TICKET                   => :airTicket,
          P_AIR_ROUTE                    => :airRoute,
          P_TRAVEL_DATE                  => :travelDate,
          P_TRAVEL_END_DATE              => :travelEndDate,
          P_NAME_OF_REPLACEMENT          => :nameOfReplacement,
          P_CONTACT_DETAILS_DURING_LEAVE => :contactDetailsDuringLeave,
          P_DUTY_RESUME_DATE             => :dutyResumeDate,
          P_ACTUAL_RESUME_DATE           => :actualResumeDate,
          P_HOD                          => :hod,
          P_IMMEDIATE_SUPERVISOR         => :immediateSupervisor,
          P_DEPT_HEAD                    => :deptHead,
          P_LAST_ACTION                  => :lastAction,
          P_CREATED_BY                   => :createdBy,
          P_UUID                         => :uuid,
          P_FLOW_CODE                    => :flowCode,
          P_NEXT_ACTION_BY               => :nextActionBy,
          P_SENTBACK_HISTORY             => :sentbackHistory,
          P_CANCEL_REMARK                => :cancelRemark,
          P_LEAVE_DAYS                   => :leaveDays,
          P_FLOW_LEVEL_INITIAL           => :flowLevelInitial,
          P_FLOW_LEVEL_RUNNING           => :flowLevelRunning,
          P_FLOW_LEVEL_FINAL             => :flowLevelFinal,
          P_SQL_OUT                      => v_sql,
          P_REQUEST_NUMBER_OUT           => v_req
        );
        :outSql := v_sql;
        :outRequestNumber := v_req;
      END;
      `,
      {
        loginId: body.loginId,
        companyCode: body.companyCode,
        requestNumber: str(body.requestNumber),
        employeeCode: str(body.employeeCode),
        employeeName: str(body.employeeName),
        leaveType: str(body.leaveType),
        requestDate: str(body.requestDate),
        leaveStartDate: str(body.leaveStartDate),
        leaveEndDate: str(body.leaveEndDate),
        remarks: str(body.remarks),
        halfDay: str(body.halfDay),
        leaveAllowance: str(body.leaveAllowance),
        advPayment: str(body.advPayment),
        causeType: str(body.causeType),
        airTicket: str(body.airTicket),
        airRoute: str(body.airRoute),
        travelDate: str(body.travelDate),
        travelEndDate: str(body.travelEndDate),
        nameOfReplacement: str(body.nameOfReplacement),
        contactDetailsDuringLeave: str(body.contactDetailsDuringLeave),
        dutyResumeDate: str(body.dutyResumeDate),
        actualResumeDate: str(body.actualResumeDate),
        hod: str(body.hod),
        immediateSupervisor: str(body.immediateSupervisor),
        deptHead: str(body.deptHead),
        lastAction: str(body.lastAction),
        createdBy: str(body.createdBy),
        uuid: str(body.uuid),
        flowCode: str(body.flowCode),
        nextActionBy: str(body.nextActionBy),
        sentbackHistory: str(body.sentbackHistory),
        cancelRemark: str(body.cancelRemark),
        leaveDays: num(body.leaveDays),
        flowLevelInitial: num(body.flowLevelInitial),
        flowLevelRunning: num(body.flowLevelRunning),
        flowLevelFinal: num(body.flowLevelFinal),

        outSql: { dir: oracledb.BIND_OUT, type: oracledb.STRING, maxSize: 32767 },
        outRequestNumber: { dir: oracledb.BIND_OUT, type: oracledb.STRING, maxSize: 50 },
      }
    );

    const outBinds = result.outBinds as { outSql: string | null; outRequestNumber: string | null };
    const dynamicSql = outBinds?.outSql;
    const savedRequestNumber = outBinds?.outRequestNumber ?? "";

    if (!dynamicSql) {
      res.status(400).json({ success: false, message: "Procedure returned no SQL" });
      return;
    }

    console.log("Generated INSERT/UPDATE SQL:", dynamicSql);

    const fetchLeaveRow = async () => {
      const r = await connection.execute(
        `SELECT * FROM LEAVE_REQUEST_FLOW WHERE COMPANY_CODE = :companyCode AND REQUEST_NUMBER = :requestNumber`,
        { companyCode: body.companyCode, requestNumber: savedRequestNumber },
        { outFormat: oracledb.OUT_FORMAT_OBJECT, fetchAsString: [oracledb.CLOB] }
      );
      return r.rows?.[0];
    };

    // 2) Status before this save, so HR is only called when this save flips it to YES
    let wasApproved = false;
    if (savedRequestNumber) {
      const before = await fetchLeaveRow(); // undefined for a brand-new request
      wasApproved = String(before?.FINAL_APPROVED ?? "").toUpperCase() === "YES";
    }

    // 3) Execute INSERT / UPDATE (the trigger sets FINAL_APPROVED on update)
    await connection.execute(dynamicSql, [], { autoCommit: true });

    // 4) If this save made the request fully approved, push it to the HR API
    if (savedRequestNumber && !wasApproved) {
      const row = await fetchLeaveRow();

      if (row && String(row.FINAL_APPROVED ?? "").toUpperCase() === "YES") {
        console.log("Sending approved leave request to HR API:", savedRequestNumber);
        try {
          await HrService.insertLeaveRequest(rowToLeaveRequest(row));
        } catch (hrErr: any) {
          // DB save already committed; don't fail the user's request
          console.error("HR insertLeaveRequest failed:", hrErr.message);
        }
      }
    }

    res.json({
      success: true,
      message: "Record inserted / updated successfully",
      requestNumber: savedRequestNumber,
    });
  } catch (error: any) {
    console.error("Oracle Error:", error);
    res.status(500).json({
      success: false,
      message: "Failed to execute insert/update",
      details: error.message,
    });
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error("Connection close error:", err);
      }
    }
  }
};