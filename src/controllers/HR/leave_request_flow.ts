/** Request body for saving (insert / update) a leave request. */
interface SaveLeaveRequestBody {
  loginId: string;

  companyCode: string;
  requestNumber?: string; // blank = new request, number is generated by the procedure
  employeeCode: string;
  employeeName?: string;
  leaveType?: string;
  requestDate?: string;
  leaveStartDate?: string;
  leaveEndDate?: string;
  remarks?: string;
  halfDay?: string;
  leaveAllowance?: string;
  advPayment?: string;
  causeType?: string;
  airTicket?: string;
  airRoute?: string;
  travelDate?: string;
  travelEndDate?: string;
  nameOfReplacement?: string;
  contactDetailsDuringLeave?: string;
  dutyResumeDate?: string;
  actualResumeDate?: string;
  hod?: string;
  immediateSupervisor?: string;
  deptHead?: string;
  lastAction?: string; // SAVEASDRAFT / SUBMIT / SENTBACK / REJECTED / CANCEL ...
  createdBy?: string;
  uuid?: string;
  flowCode?: string;
  nextActionBy?: string; // SENTBACK only
  sentbackHistory?: string; // SENTBACK only
  cancelRemark?: string; // REJECTED / CANCEL

  leaveDays?: number;
  flowLevelInitial?: number;
  flowLevelRunning?: number;
  flowLevelFinal?: number;
}

// ---------- helpers ----------

const str = (v: unknown): string | null =>
  v === undefined || v === null || String(v).trim() === "" ? null : String(v);

const num = (v: unknown): number | null => {
  if (v === undefined || v === null || v === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
};

const pad = (n: number) => String(n).padStart(2, "0");

// Local-time string so HrService's toISOString() can't shift the date back a day
const dateToLocalString = (d: Date) =>
  `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
  `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;

// "YYYY-MM-DD" part of a date string / Date (local time), or null if it can't be parsed
const toDatePart = (v: unknown): string | null => {
  const s = str(v);
  if (!s) return null;
  const m = s.match(/^\d{4}-\d{2}-\d{2}/);
  if (m) return m[0];
  const d = new Date(s);
  return Number.isNaN(d.getTime()) ? null : dateToLocalString(d).slice(0, 10);
};

const todayDatePart = (): string => dateToLocalString(new Date()).slice(0, 10);

// Tenant whose approved leave requests are pushed to the HR API (lower-case)
const HR_SYNC_TENANT = "wmsdev_tenant";

/** Outcome of the HR push, returned to the client. */
interface HrSyncResult {
  attempted: boolean;
  success?: boolean;
  action?: "INSERT" | "UPDATE_RESUME";
  message?: string;
}

// Turn an HR API / axios error into one short, readable line
// e.g. "Database error: ORA-20100: Resume date cannot be future date.\nORA-06512: ..."
//   -> "Resume date cannot be future date."
const extractHrErrorMessage = (err: any): string => {
  const data = err?.response?.data;
  let msg: unknown =
    typeof data === "string" ? data : data?.message ?? data?.error ?? err?.message;
  if (typeof msg !== "string" || !msg.trim()) msg = "Unknown error from HR API";
  const firstLine = (msg as string).split("\n")[0].trim();
  return (
    firstLine
      .replace(/^Database error:\s*/i, "")
      .replace(/^ORA-\d+:\s*/i, "")
      .trim() || "Unknown error from HR API"
  );
};

// LEAVE_START_DATE -> leaveStartDate, Date -> local string
const rowToLeaveRequest = (row: Record<string, any>): LeaveRequestFlow => {
  const out: Record<string, any> = {};
  for (const [key, value] of Object.entries(row)) {
    const camel = key.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
    out[camel] = value instanceof Date ? dateToLocalString(value) : value;
  }
  return out as LeaveRequestFlow;
};

// ---------- controller ----------

export const leaveRequestFlow = async (
  req: Request,
  res: Response
): Promise<void> => {
  let connection: oracledb.Connection | undefined;

  try {
    const body = (req.body ?? {}) as SaveLeaveRequestBody;

    if (!body.loginId) {
      res.status(400).json({ success: false, message: "Missing required field 'loginId'" });
      return;
    }
    if (!body.companyCode) {
      res.status(400).json({ success: false, message: "Missing required field 'companyCode'" });
      return;
    }

    // HR rejects a future actual resume date (ORA-20100), so stop here, before anything is
    // saved or sent to HR, and tell the client straight away.
    const actualResumeDay = toDatePart(body.actualResumeDate);
    if (actualResumeDay && actualResumeDay > todayDatePart()) {
      res.status(400).json({
        success: false,
        message: "Actual resume date cannot be a future date",
      });
      return;
    }

    // Resolve tenantId from context or fallback to loginId lookup
    let tenantId: string | undefined;
    try {
      tenantId = getCurrentTenantId();
    } catch {
      // no tenant in request context; fall back to the loginId lookup below
    }
    if (!tenantId) {
      tenantId = await TenantManager.getTenantForUser(body.loginId);
    }

    if (!tenantId) {
      res.status(400).json({ success: false, message: "Tenant not found for request" });
      return;
    }

    // `conn` is a const so TypeScript keeps it non-undefined inside the closures below
    const conn: oracledb.Connection = await TenantManager.getConnection(tenantId);
    connection = conn;

    // 1) Ask the procedure to build the INSERT / UPDATE SQL
    const result = await conn.execute(
      `
      DECLARE
        v_sql CLOB;
        v_req VARCHAR2(50);
      BEGIN
        PROC_BUILD_DYNAMIC_INS_UPD_LEAVE_REQUEST_FLOW(
          P_LOGIN_ID                     => :loginId,
          P_COMPANY_CODE                 => :companyCode,
          P_REQUEST_NUMBER               => :requestNumber,
          P_EMPLOYEE_CODE                => :employeeCode,
          P_EMPLOYEE_NAME                => :employeeName,
          P_LEAVE_TYPE                   => :leaveType,
          P_REQUEST_DATE                 => :requestDate,
          P_LEAVE_START_DATE             => :leaveStartDate,
          P_LEAVE_END_DATE               => :leaveEndDate,
          P_REMARKS                      => :remarks,
          P_HALF_DAY                     => :halfDay,
          P_LEAVE_ALLOWANCE              => :leaveAllowance,
          P_ADV_PAYMENT                  => :advPayment,
          P_CAUSE_TYPE                   => :causeType,
          P_AIR_TICKET                   => :airTicket,
          P_AIR_ROUTE                    => :airRoute,
          P_TRAVEL_DATE                  => :travelDate,
          P_TRAVEL_END_DATE              => :travelEndDate,
          P_NAME_OF_REPLACEMENT          => :nameOfReplacement,
          P_CONTACT_DETAILS_DURING_LEAVE => :contactDetailsDuringLeave,
          P_DUTY_RESUME_DATE             => :dutyResumeDate,
          P_ACTUAL_RESUME_DATE           => :actualResumeDate,
          P_HOD                          => :hod,
          P_IMMEDIATE_SUPERVISOR         => :immediateSupervisor,
          P_DEPT_HEAD                    => :deptHead,
          P_LAST_ACTION                  => :lastAction,
          P_CREATED_BY                   => :createdBy,
          P_UUID                         => :uuid,
          P_FLOW_CODE                    => :flowCode,
          P_NEXT_ACTION_BY               => :nextActionBy,
          P_SENTBACK_HISTORY             => :sentbackHistory,
          P_CANCEL_REMARK                => :cancelRemark,
          P_LEAVE_DAYS                   => :leaveDays,
          P_FLOW_LEVEL_INITIAL           => :flowLevelInitial,
          P_FLOW_LEVEL_RUNNING           => :flowLevelRunning,
          P_FLOW_LEVEL_FINAL             => :flowLevelFinal,
          P_SQL_OUT                      => v_sql,
          P_REQUEST_NUMBER_OUT           => v_req
        );
        :outSql := v_sql;
        :outRequestNumber := v_req;
      END;
      `,
      {
        loginId: body.loginId,
        companyCode: body.companyCode,
        requestNumber: str(body.requestNumber),
        employeeCode: str(body.employeeCode),
        employeeName: str(body.employeeName),
        leaveType: str(body.leaveType),
        requestDate: str(body.requestDate),
        leaveStartDate: str(body.leaveStartDate),
        leaveEndDate: str(body.leaveEndDate),
        remarks: str(body.remarks),
        halfDay: str(body.halfDay),
        leaveAllowance: str(body.leaveAllowance),
        advPayment: str(body.advPayment),
        causeType: str(body.causeType),
        airTicket: str(body.airTicket),
        airRoute: str(body.airRoute),
        travelDate: str(body.travelDate),
        travelEndDate: str(body.travelEndDate),
        nameOfReplacement: str(body.nameOfReplacement),
        contactDetailsDuringLeave: str(body.contactDetailsDuringLeave),
        dutyResumeDate: str(body.dutyResumeDate),
        actualResumeDate: str(body.actualResumeDate),
        hod: str(body.hod),
        immediateSupervisor: str(body.immediateSupervisor),
        deptHead: str(body.deptHead),
        lastAction: str(body.lastAction),
        createdBy: str(body.createdBy),
        uuid: str(body.uuid),
        flowCode: str(body.flowCode),
        nextActionBy: str(body.nextActionBy),
        sentbackHistory: str(body.sentbackHistory),
        cancelRemark: str(body.cancelRemark),
        leaveDays: num(body.leaveDays),
        flowLevelInitial: num(body.flowLevelInitial),
        flowLevelRunning: num(body.flowLevelRunning),
        flowLevelFinal: num(body.flowLevelFinal),

        outSql: { dir: oracledb.BIND_OUT, type: oracledb.STRING, maxSize: 32767 },
        outRequestNumber: { dir: oracledb.BIND_OUT, type: oracledb.STRING, maxSize: 50 },
      }
    );

    const outBinds = result.outBinds as unknown as {
      outSql: string | null;
      outRequestNumber: string | null;
    };
    const dynamicSql = outBinds?.outSql;
    const savedRequestNumber = outBinds?.outRequestNumber ?? "";

    if (!dynamicSql) {
      res.status(400).json({ success: false, message: "Procedure returned no SQL" });
      return;
    }

    console.log("Generated INSERT/UPDATE SQL:", dynamicSql);
    await conn.execute(dynamicSql, [], { autoCommit: true });

    console.log("Leave request saved successfully. Request Number:", savedRequestNumber);

    // HR sync outcome, returned to the client
    let hrSync: HrSyncResult = { attempted: false };

    // Push to HR only for HR_SYNC_TENANT, and only when the request is fully approved
    if (savedRequestNumber && tenantId.toLowerCase() === HR_SYNC_TENANT) {
      try {
        const fetchSql = `SELECT * FROM LEAVE_REQUEST_FLOW WHERE COMPANY_CODE = :companyCode AND REQUEST_NUMBER = :requestNumber`;
        const fetchResult = await conn.execute<any>(
          fetchSql,
          { companyCode: body.companyCode, requestNumber: savedRequestNumber },
          { outFormat: oracledb.OUT_FORMAT_OBJECT }
        );
        const row = fetchResult.rows?.[0];

        if (row && String(row.FINAL_APPROVED ?? "").toUpperCase() === "YES") {
          const leaveRequest = rowToLeaveRequest(row);

          // Both resume dates present -> request already exists in HR, so update instead of insert.
          // LeaveResumeDatesUpdate expects Date objects, so take them from the raw row
          // (rowToLeaveRequest converts dates to strings).
          const dutyResumeDate: Date | null = row.DUTY_RESUME_DATE
            ? new Date(row.DUTY_RESUME_DATE)
            : null;
          const actualResumeDate: Date | null = row.ACTUAL_RESUME_DATE
            ? new Date(row.ACTUAL_RESUME_DATE)
            : null;
          const hasResumeDates = !!dutyResumeDate && !!actualResumeDate;

          try {
            if (dutyResumeDate && actualResumeDate) {
              console.log("Sending resume dates update to HR API:", savedRequestNumber);
              await HrService.updateLeaveResume({
                requestNumber: savedRequestNumber,
                dutyResumeDate,
                actualResumeDate,
              });
              console.log("HR updateLeaveResume succeeded for", savedRequestNumber);
              hrSync = {
                attempted: true,
                success: true,
                action: "UPDATE_RESUME",
                message: "Resume dates updated in HR",
              };
            } else {
              console.log("Sending approved leave request to HR API:", savedRequestNumber);
              await HrService.insertLeaveRequest(leaveRequest);
              console.log("HR insertLeaveRequest succeeded for", savedRequestNumber);
              hrSync = {
                attempted: true,
                success: true,
                action: "INSERT",
                message: "Leave request sent to HR",
              };
            }
          } catch (hrErr: any) {
            // DB already committed – log but do not fail the client response
            console.error(
              `HR ${hasResumeDates ? "updateLeaveResume" : "insertLeaveRequest"} failed:`,
              hrErr?.message ?? hrErr
            );
            hrSync = {
              attempted: true,
              success: false,
              action: hasResumeDates ? "UPDATE_RESUME" : "INSERT",
              message: extractHrErrorMessage(hrErr),
            };
          }
        } else {
          // Not final-approved yet, nothing to send to HR
          hrSync = {
            attempted: false,
            message: "HR sync skipped: request is not final approved yet",
          };
        }
      } catch (fetchErr: any) {
        console.error("Failed to fetch leave request for HR push:", fetchErr?.message ?? fetchErr);
        hrSync = {
          attempted: true,
          success: false,
          message: "Could not read the saved request to send it to HR",
        };
      }
    }

    // DB save already succeeded, so success stays true; HR problems are reported in the message
    let message = "Record inserted / updated successfully";
    if (hrSync.attempted && hrSync.success) {
      message = `Record saved successfully. ${hrSync.message}.`;
    } else if (hrSync.attempted && !hrSync.success) {
      message = `Record saved, but HR sync failed: ${hrSync.message}`;
    }

    res.json({
      success: true,
      message,
      requestNumber: savedRequestNumber,
      hrSync,
    });
  } catch (error: any) {
    console.error("Oracle Error:", error);
    res.status(500).json({
      success: false,
      message: "Failed to execute insert/update",
      details: error.message,
    });
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error("Connection close error:", err);
      }
    }
  }
};